"""
Dataset generation pipeline.

Usage:
    python build_dataset.py [--split train|val|test] [--num_samples N]
                            [--grid_w W] [--grid_h H] [--num_agents A]
                            [--obstacle_prob P] [--seed S] [--out_dir DIR]
                            [--num_workers K]

Each sample is generated by:
  1. generate_random_map    -> map_dims
  2. sample_agents_goals    -> agents, goals
  3. compute_distance_matrix -> D  (skip if any entry is inf)
  4. get_ground_truth        -> Y  (skip on solver failure)
  5. normalize_D             -> D_norm in [0, 1]

Output: {out_dir}/{split}/D_matrices.npy  shape (S, N, N)
        {out_dir}/{split}/Y_matrices.npy  shape (S, N, N)
"""

import argparse
import multiprocessing
import os
import numpy as np
from tqdm import tqdm

from grid_gen import generate_random_map, sample_agents_goals
from distance import compute_distance_matrix, compute_goal_distance_matrix, normalize_D
from oracle import get_ground_truth

_CHUNK = 64  # tasks submitted to the pool at a time


def _try_one_sample(task):
    """
    Single-sample generation attempt.  Runs in a worker process.
    Returns (D_norm, G_norm, Y) on success, None on rejection.

    Each worker has its own process address space, so os.chdir inside
    solver_wrapper is safe — it does not affect other workers.
    """
    grid_w, grid_h, num_agents, obstacle_prob, seed, config_str = task
    try:
        map_dims = generate_random_map(grid_w, grid_h, obstacle_prob, seed=seed)
        agents, goals = sample_agents_goals(map_dims, num_agents, seed=seed)
    except ValueError:
        return None

    D = compute_distance_matrix(map_dims, agents, goals)
    if np.any(D == float("inf")):
        return None

    G = compute_goal_distance_matrix(map_dims, goals)
    if np.any(G == float("inf")):
        return None

    result = get_ground_truth(map_dims, agents, goals, config_str=config_str)
    if result is None:
        return None

    Y, _ = result
    D_norm = normalize_D(D, grid_w, grid_h)
    G_norm = normalize_D(G, grid_w, grid_h)
    return D_norm, G_norm, Y


# Mix the split into the seed: with a shared base seed, train/val/test would
# otherwise draw the same per-sample seed stream, making test a subset of train.
_SPLIT_OFFSET = {"train": 0, "val": 1, "test": 2}


def _split_rng(base_seed: int, split: str) -> np.random.Generator:
    return np.random.default_rng([base_seed, _SPLIT_OFFSET[split]])


def generate_split(
    num_samples: int,
    grid_w: int,
    grid_h: int,
    num_agents: int,
    obstacle_prob: float,
    base_seed: int,
    split: str,
    out_dir: str,
    num_workers: int = 1,
) -> None:
    save_dir = os.path.join(out_dir, split)
    os.makedirs(save_dir, exist_ok=True)

    rng = _split_rng(base_seed, split)
    D_list, G_list, Y_list = [], [], []
    attempts = 0

    def _next_tasks(n):
        nonlocal attempts
        tasks = []
        for _ in range(n):
            seed = int(rng.integers(0, 2**31))
            config_str = f"{split}_{attempts}"
            tasks.append((grid_w, grid_h, num_agents, obstacle_prob, seed, config_str))
            attempts += 1
        return tasks

    with tqdm(total=num_samples, desc=f"Generating {split}") as pbar:
        if num_workers <= 1:
            while len(D_list) < num_samples:
                for task in _next_tasks(_CHUNK):
                    if len(D_list) >= num_samples:
                        break
                    result = _try_one_sample(task)
                    if result is not None:
                        D_list.append(result[0])
                        G_list.append(result[1])
                        Y_list.append(result[2])
                        pbar.update(1)
        else:
            with multiprocessing.Pool(num_workers) as pool:
                while len(D_list) < num_samples:
                    tasks = _next_tasks(_CHUNK)
                    for result in pool.imap_unordered(_try_one_sample, tasks):
                        if result is not None and len(D_list) < num_samples:
                            D_list.append(result[0])
                            G_list.append(result[1])
                            Y_list.append(result[2])
                            pbar.update(1)

    np.save(os.path.join(save_dir, "D_matrices.npy"), np.array(D_list, dtype=np.float32))
    np.save(os.path.join(save_dir, "G_matrices.npy"), np.array(G_list, dtype=np.float32))
    np.save(os.path.join(save_dir, "Y_matrices.npy"), np.array(Y_list, dtype=np.float32))
    print(f"Saved {num_samples} samples to {save_dir}/ ({attempts} attempts total)")


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate MCPF goal-allocation dataset")
    parser.add_argument("--split", choices=["train", "val", "test"], default="train")
    parser.add_argument("--num_samples", type=int, default=10_000)
    parser.add_argument("--grid_w", type=int, default=5)
    parser.add_argument("--grid_h", type=int, default=5)
    parser.add_argument("--num_agents", type=int, default=2)
    parser.add_argument("--obstacle_prob", type=float, default=0.1)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--out_dir", type=str, default=os.path.join("..", "data"))
    parser.add_argument("--num_workers", type=int, default=1,
                        help="Parallel solver workers (each is a separate process)")
    args = parser.parse_args()

    generate_split(
        num_samples=args.num_samples,
        grid_w=args.grid_w,
        grid_h=args.grid_h,
        num_agents=args.num_agents,
        obstacle_prob=args.obstacle_prob,
        base_seed=args.seed,
        split=args.split,
        out_dir=args.out_dir,
        num_workers=args.num_workers,
    )


if __name__ == "__main__":
    multiprocessing.set_start_method("spawn", force=True)
    main()
