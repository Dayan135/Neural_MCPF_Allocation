"""
Dataset generation pipeline.

Usage:
    python build_dataset.py [--split train|val|test] [--num_samples N]
                            [--grid_w W] [--grid_h H] [--num_agents A]
                            [--num_goals M] [--obstacle_prob P]
                            [--grid_w_max W2] [--grid_h_max H2]
                            [--obstacle_prob_max P2] [--map_file NAME]
                            [--seed S] [--out_dir DIR] [--num_workers K]
                            [--instance_timeout SECONDS]

--num_goals defaults to --num_agents (the N=M case from all current experiments).

When --grid_w_max / --grid_h_max are given, grid width/height are sampled
uniformly per instance from [grid_w, grid_w_max] / [grid_h, grid_h_max].
When --obstacle_prob_max is given, obstacle probability is sampled uniformly
per instance from [obstacle_prob, obstacle_prob_max].
These options let a single run produce a diverse dataset over grid sizes and
wall densities while keeping D/G/Y tensors shape (N, M) / (M, M) / (N, M).

With --map_file, the grid is a fixed MovingAI .map (one of the vendored benchmark
maps) instead of a freshly generated random grid; only agent/goal placement varies
per instance. This option is incompatible with the grid/obstacle range options.

Each sample is generated by:
  1. generate_random_map (or the fixed --map_file) -> map_dims
  2. sample_agents_goals    -> agents, goals
  3. compute_distance_matrix -> D  (skip if any entry is inf)
  4. get_ground_truth        -> Y  (skip on solver failure)
  5. normalize_D             -> D_norm  (divided by (W-1)+(H-1) of that instance)

Output: {out_dir}/{split}/D_matrices.npy  shape (S, N, M)
        {out_dir}/{split}/G_matrices.npy  shape (S, M, M)
        {out_dir}/{split}/Y_matrices.npy  shape (S, N, M)
"""

import argparse
import multiprocessing
import os
import numpy as np
from tqdm import tqdm

from grid_gen import generate_random_map, sample_agents_goals, load_map_file
from distance import compute_distance_matrix, compute_goal_distance_matrix, normalize_D
from oracle import get_ground_truth

_CHUNK = 64  # tasks submitted to the pool at a time


def _try_one_sample(task):
    """
    Single-sample generation attempt.  Runs in a worker process.
    Returns (D_norm, G_norm, Y) on success, None on rejection.

    Each worker has its own process address space, so os.chdir inside
    solver_wrapper is safe — it does not affect other workers.
    """
    (grid_w, grid_h, num_agents, num_goals, obstacle_prob, seed, config_str,
     fixed_map, instance_timeout) = task
    try:
        # fixed_map (a preloaded MapAndDims dict) pins the grid; otherwise each
        # instance gets a fresh random map. grid_w/grid_h are the fixed map's
        # Cols/Rows in that case, so normalize_D below stays correct.
        map_dims = fixed_map if fixed_map is not None else generate_random_map(grid_w, grid_h, obstacle_prob, seed=seed)
        agents, goals = sample_agents_goals(map_dims, num_agents, M=num_goals, seed=seed)
    except ValueError:
        return None

    D = compute_distance_matrix(map_dims, agents, goals)
    if np.any(D == float("inf")):
        return None

    G = compute_goal_distance_matrix(map_dims, goals)
    if np.any(G == float("inf")):
        return None

    result = get_ground_truth(map_dims, agents, goals, config_str=config_str,
                              instance_timeout=instance_timeout)
    if result is None:
        return None

    Y, _ = result
    # Normalize by this instance's grid dimensions (correct when W/H vary per instance).
    D_norm = normalize_D(D, grid_w, grid_h)
    G_norm = normalize_D(G, grid_w, grid_h)
    return D_norm, G_norm, Y


# Mix the split into the seed: with a shared base seed, train/val/test would
# otherwise draw the same per-sample seed stream, making test a subset of train.
_SPLIT_OFFSET = {"train": 0, "val": 1, "test": 2}


def _split_rng(base_seed: int, split: str, resume_offset: int = 0) -> np.random.Generator:
    # resume_offset shifts the stream on a resumed run so it doesn't just
    # replay (and re-solve) the same instances that already succeeded.
    return np.random.default_rng([base_seed, _SPLIT_OFFSET[split], resume_offset])


def _load_existing(save_dir: str) -> tuple[list, list, list]:
    """Load a prior (possibly partial) save for this split, if one exists —
    lets a re-submitted job resume instead of re-solving already-done instances."""
    paths = [os.path.join(save_dir, f"{name}.npy") for name in ("D_matrices", "G_matrices", "Y_matrices")]
    if not all(os.path.exists(p) for p in paths):
        return [], [], []
    D, G, Y = (np.load(p) for p in paths)
    return list(D), list(G), list(Y)


def _save_checkpoint(save_dir: str, D_list: list, G_list: list, Y_list: list) -> None:
    np.save(os.path.join(save_dir, "D_matrices.npy"), np.array(D_list, dtype=np.float32))
    np.save(os.path.join(save_dir, "G_matrices.npy"), np.array(G_list, dtype=np.float32))
    np.save(os.path.join(save_dir, "Y_matrices.npy"), np.array(Y_list, dtype=np.float32))


def generate_split(
    num_samples: int,
    grid_w: int,
    grid_h: int,
    num_agents: int,
    num_goals: int,
    obstacle_prob: float,
    base_seed: int,
    split: str,
    out_dir: str,
    num_workers: int = 1,
    grid_w_max: int | None = None,
    grid_h_max: int | None = None,
    obstacle_prob_max: float | None = None,
    fixed_map: dict | None = None,
    instance_timeout: float = 0.0,
) -> None:
    save_dir = os.path.join(out_dir, split)
    os.makedirs(save_dir, exist_ok=True)

    # With a fixed map, the grid is constant — only placement varies. Use the
    # map's own dimensions so normalize_D divides by the right diagonal.
    if fixed_map is not None:
        grid_w, grid_h = fixed_map["Cols"], fixed_map["Rows"]

    D_list, G_list, Y_list = _load_existing(save_dir)
    resume_offset = len(D_list)
    if resume_offset >= num_samples:
        print(f"{save_dir}/ already has {resume_offset} >= {num_samples} samples, skipping")
        return
    if resume_offset:
        print(f"Resuming {save_dir}/: {resume_offset} samples already saved, "
              f"generating {num_samples - resume_offset} more")

    rng = _split_rng(base_seed, split, resume_offset)
    attempts = 0

    def _next_tasks(n):
        nonlocal attempts
        tasks = []
        for _ in range(n):
            seed = int(rng.integers(0, 2**31))
            w = int(rng.integers(grid_w, grid_w_max + 1)) if grid_w_max is not None else grid_w
            h = int(rng.integers(grid_h, grid_h_max + 1)) if grid_h_max is not None else grid_h
            p = float(rng.uniform(obstacle_prob, obstacle_prob_max)) if obstacle_prob_max is not None else obstacle_prob
            config_str = f"{split}_{resume_offset}_{attempts}"
            tasks.append((w, h, num_agents, num_goals, p, seed, config_str,
                         fixed_map, instance_timeout))
            attempts += 1
        return tasks

    with tqdm(total=num_samples, initial=resume_offset, desc=f"Generating {split}") as pbar:
        if num_workers <= 1:
            while len(D_list) < num_samples:
                for task in _next_tasks(_CHUNK):
                    if len(D_list) >= num_samples:
                        break
                    result = _try_one_sample(task)
                    if result is not None:
                        D_list.append(result[0])
                        G_list.append(result[1])
                        Y_list.append(result[2])
                        pbar.update(1)
                _save_checkpoint(save_dir, D_list, G_list, Y_list)
        else:
            with multiprocessing.Pool(num_workers) as pool:
                while len(D_list) < num_samples:
                    tasks = _next_tasks(_CHUNK)
                    for result in pool.imap_unordered(_try_one_sample, tasks):
                        if result is not None and len(D_list) < num_samples:
                            D_list.append(result[0])
                            G_list.append(result[1])
                            Y_list.append(result[2])
                            pbar.update(1)
                    _save_checkpoint(save_dir, D_list, G_list, Y_list)

    _save_checkpoint(save_dir, D_list, G_list, Y_list)
    print(f"Saved {len(D_list)} samples to {save_dir}/ ({resume_offset} resumed + "
          f"{attempts} new attempts)")


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate MCPF goal-allocation dataset")
    parser.add_argument("--split", choices=["train", "val", "test"], default="train")
    parser.add_argument("--num_samples", type=int, default=10_000)
    parser.add_argument("--grid_w", type=int, default=5)
    parser.add_argument("--grid_h", type=int, default=5)
    parser.add_argument("--num_agents", type=int, default=2)
    parser.add_argument("--num_goals", type=int, default=None,
                        help="Number of goals (default: same as --num_agents)")
    parser.add_argument("--obstacle_prob", type=float, default=0.1)
    parser.add_argument("--grid_w_max", type=int, default=None,
                        help="If set, grid width is sampled uniformly from [grid_w, grid_w_max] per instance")
    parser.add_argument("--grid_h_max", type=int, default=None,
                        help="If set, grid height is sampled uniformly from [grid_h, grid_h_max] per instance")
    parser.add_argument("--obstacle_prob_max", type=float, default=None,
                        help="If set, obstacle prob is sampled uniformly from [obstacle_prob, obstacle_prob_max] per instance")
    parser.add_argument("--map_file", type=str, default=None,
                        help="Load a fixed MovingAI .map (bare name resolves against RobustMCPF/Maps/) "
                             "instead of generating random grids. Incompatible with the grid/obstacle range options.")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--out_dir", type=str, default=os.path.join("..", "data"))
    parser.add_argument("--num_workers", type=int, default=1,
                        help="Parallel solver workers (each is a separate process)")
    parser.add_argument("--instance_timeout", type=float, default=0.0,
                        help="Wall-clock cap (seconds) per solver call, 0 = disabled. "
                             "Needed at N/M >= ~100: cbs_node_budget alone doesn't bound "
                             "wall time once individual CBS node expansions get slow.")
    args = parser.parse_args()

    num_goals = args.num_goals if args.num_goals is not None else args.num_agents

    fixed_map = None
    if args.map_file is not None:
        if any(v is not None for v in (args.grid_w_max, args.grid_h_max, args.obstacle_prob_max)):
            parser.error("--map_file is incompatible with --grid_w_max / --grid_h_max / --obstacle_prob_max "
                         "(a fixed map has no grid/obstacle range to sample).")
        fixed_map = load_map_file(args.map_file)
        print(f"Loaded fixed map {args.map_file}: {fixed_map['Cols']}x{fixed_map['Rows']}, "
              f"{sum(fixed_map['Map'])} obstacles")

    generate_split(
        num_samples=args.num_samples,
        grid_w=args.grid_w,
        grid_h=args.grid_h,
        num_agents=args.num_agents,
        num_goals=num_goals,
        obstacle_prob=args.obstacle_prob,
        base_seed=args.seed,
        split=args.split,
        out_dir=args.out_dir,
        num_workers=args.num_workers,
        grid_w_max=args.grid_w_max,
        grid_h_max=args.grid_h_max,
        obstacle_prob_max=args.obstacle_prob_max,
        fixed_map=fixed_map,
        instance_timeout=args.instance_timeout,
    )


if __name__ == "__main__":
    multiprocessing.set_start_method("spawn", force=True)
    main()
